/**
 * Emits the SQL that seeds `business_types` from BUSINESS_TYPES.
 *
 * The TypeScript seed is the source of truth for system verticals — it is what
 * the tests hold to the design file, character for character. Postgres needs
 * the same records so Edge Functions and onboarding can read a vertical the
 * client has never loaded, and so custom (no-code) verticals have somewhere to
 * live beside the built-in ones.
 *
 * Two copies means drift. This script is the only sanctioned way to make the
 * second one: change the seed, regenerate into a NEW migration, commit both.
 * Never hand-edit the emitted SQL.
 *
 *   node scripts/generate-seed-migration.mjs > ../../supabase/migrations/<ts>_seed_business_types.sql
 *
 * Requires Node >= 22.6 (native TypeScript type stripping).
 */
import { BUSINESS_TYPES } from "../src/seed/business-types.ts";

/** Postgres string literal. Doubling the quote is the whole escape rule. */
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

const rows = BUSINESS_TYPES.map((config) => {
  const json = JSON.stringify(config, null, 2);
  return `  (${lit(config.businessType)}, ${lit(config.label)}, true, ${lit(json)}::jsonb)`;
}).join(",\n");

const keys = BUSINESS_TYPES.map((c) => lit(c.businessType)).join(", ");

process.stdout
  .write(`-- Seed business_types with the 18 verticals from the design.
--
-- GENERATED by packages/core/scripts/generate-seed-migration.mjs — do not edit
-- by hand. Regenerate from the seed and add a new migration instead.
--
-- Phase 3 seeded 18 placeholder verticals with '{}' config and invented keys
-- (apparel, bakery, salon, clinic, agriculture, ...). The design names a
-- different 18 (medical, kirana, mobile, hotel, catering, manufacturing,
-- garments, retail, distributor). The design is authoritative, so this
-- reconciles the table to it and fills in the config the engine reads.
--
-- Nothing hardcodes a key: onboarding lists whatever rows exist here, and
-- create_workspace resolves the key it is handed. So keys may change.

insert into public.business_types (key, label, is_system, config)
values
${rows}
on conflict (key) do update
  set label = excluded.label,
      config = excluded.config,
      is_system = true;

-- Retire the placeholder verticals. Only ever touches system rows that no org
-- points at — an org on a retired key keeps it rather than silently becoming a
-- pharmacy, and a tenant's own custom vertical (is_system = false) is never in
-- scope here.
delete from public.business_types bt
where bt.is_system = true
  and bt.key not in (${keys})
  and not exists (
    select 1 from public.organizations o where o.business_type_id = bt.id
  );
`);
